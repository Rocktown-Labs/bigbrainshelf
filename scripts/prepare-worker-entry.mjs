// Prepare the deployed worker entry (Book Club V2 scheduler).
//
// `astro build` emits dist/server/entry.mjs whose default export is the
// Astro fetch handler only: there is no scheduled handler, and the
// Cloudflare adapter has no custom-entrypoint option. This script:
//   1. bundles src/worker/scheduler.ts to dist/server/club-scheduler.mjs
//      with the repo's own esbuild (same single-file style as the
//      kidsbook-factory deploy),
//   2. writes dist/server/worker.mjs, a thin wrapper that re-exports
//      the Astro fetch handler and adds a `scheduled` handler that runs
//      the outbox flush + Book Club cycle pass in ctx.waitUntil.
//
// deploy.py uploads worker.mjs as the worker's main module and points
// it at the uploaded entry.mjs + club-scheduler.mjs modules. It runs
// as part of `bun run build` (see package.json) and again from
// deploy.py, so both paths produce the wrapper.

import { build } from "esbuild";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const serverDir = resolve(root, "dist/server");

await build({
  entryPoints: [resolve(root, "src/worker/scheduler.ts")],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "es2022",
  external: ["cloudflare:workers"],
  outfile: resolve(serverDir, "club-scheduler.mjs"),
});

writeFileSync(
  resolve(serverDir, "worker.mjs"),
  [
    "// Generated by scripts/prepare-worker-entry.mjs. Do not edit:",
    "// wraps the Astro entry with the Cloudflare scheduled handler,",
    "// plus edge cache headers the platform does not apply on its own:",
    "// Workers Assets answers /_astro/* with max-age=0, must-revalidate",
    "// (the dist _headers rule is not honored in the direct-upload",
    "// flow), and the zone's Cache Rules API is not writable with the",
    "// stored credential, so content-hashed assets get their immutable",
    "// lifetime here and stable brand assets get a day. HTML, /api/*,",
    "// /admin/*, /account/* and /read/* are never touched.",
    'import astroWorker from "./entry.mjs";',
    'import { handleScheduled } from "./club-scheduler.mjs";',
    "",
    "const STATIC_DAY = /^(favicon[^/]*|icon-\\d+\\.png|apple-touch-icon\\.png|logo-stacked\\.(png|svg)|og-image\\.jpg|site\\.webmanifest)$/;",
    "function cacheControlFor(path) {",
    '  if (path.startsWith("/_astro/")) return "public, max-age=31536000, immutable";',
    "  const base = path.slice(1);",
    '  if (!base.includes("/") && STATIC_DAY.test(base)) return "public, max-age=86400";',
    "  return null;",
    "}",
    "",
    "export default {",
    "  async fetch(request, env, ctx) {",
    "    const res = await astroWorker.fetch(request, env, ctx);",
    '    if ((request.method !== "GET" && request.method !== "HEAD") || res.status !== 200) return res;',
    "    let cc = null;",
    "    try { cc = cacheControlFor(new URL(request.url).pathname); } catch { cc = null; }",
    "    if (!cc) return res;",
    "    try {",
    "      const out = new Response(res.body, res);",
    '      out.headers.set("Cache-Control", cc);',
    "      return out;",
    "    } catch { return res; }",
    "  },",
    "  async scheduled(controller, env, ctx) {",
    "    ctx.waitUntil(handleScheduled(env));",
    "  },",
    "};",
    "",
  ].join("\n")
);

console.log("worker entry prepared: dist/server/worker.mjs + club-scheduler.mjs");
